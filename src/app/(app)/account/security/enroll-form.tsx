"use client";
import { useActionState, useState, useTransition } from "react";
import { Button } from "@/components/ui/button";
import { Field, Input } from "@/components/ui/input";
import { confirmEnroll, startEnroll, type EnrollState } from "../actions";

export function EnrollForm() {
  const [setup, setSetup] = useState<EnrollState>();
  const [starting, startTransition] = useTransition();
  const [state, action, pending] = useActionState<EnrollState, FormData>(confirmEnroll, undefined);
  const current = state?.factorId ? state : setup;

  if (state?.done) return <p className="text-body text-success">Two-step verification is on. You will be asked for a code at your next sign in.</p>;

  if (!current?.factorId) {
    return (
      <div className="flex flex-col items-start gap-3">
        <p className="text-body text-fg-muted">Use Google Authenticator, Microsoft Authenticator or a similar app.</p>
        {setup?.error ? <p className="text-helper text-error" role="alert">{setup.error}</p> : null}
        <Button variant="primary" loading={starting} onClick={() => startTransition(async () => setSetup(await startEnroll()))}>
          Set up
        </Button>
      </div>
    );
  }

  return (
    <form action={action} className="flex flex-col gap-4">
      <p className="text-body">Scan this code with your authenticator app, then enter the 6-digit code it shows.</p>
      {current.qr ? (
        // The QR code is an SVG data URL generated by Supabase for this setup only.
        // eslint-disable-next-line @next/next/no-img-element
        <img src={current.qr} alt="QR code for your authenticator app" className="size-44 rounded-control border border-border bg-white p-2" />
      ) : null}
      {setup?.secret ? <p className="text-helper text-fg-muted">Can&apos;t scan? Enter this key: <code className="tabular break-all">{setup.secret}</code></p> : null}
      <input type="hidden" name="factorId" value={current.factorId} />
      <input type="hidden" name="qr" value={current.qr ?? ""} />
      {state?.error ? <p className="text-helper text-error" role="alert">{state.error}</p> : null}
      <Field label="Code" htmlFor="code">
        <Input id="code" name="code" inputMode="numeric" autoComplete="one-time-code" maxLength={7} required className="tabular max-w-40 tracking-widest" />
      </Field>
      <Button type="submit" variant="primary" loading={pending} className="self-start">Turn on</Button>
    </form>
  );
}
